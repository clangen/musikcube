/* Check that public C declarations match the shared-library export allowlist.
   Without --check, print the declaration
   inventory used by the API documentation. */
const { readFileSync } = require('fs');
const { resolve, join } = require('path');
const root = resolve(__dirname, '../..');
const headers = ['abi.h', 'context.h', 'equalizer.h', 'indexer.h', 'library.h', 'output.h', 'playback.h',
  'visualizer.h', 'preferences.h', 'server.h', 'plugins.h', 'paths.h', 'musikcore.h'];
const exportedSymbols = readFileSync(join(root, 'src/musikcore/ffi/exports.txt'), 'utf8').trim().split(/\s+/).sort();
const declared = [];
const inventory = [];

/* Inventory source declarations without including private headers; comparing
   the result to the export allowlist catches accidental surface drift. */
for (const header of headers) {
  const text = readFileSync(join(root, 'include/musikcore', header), 'utf8');
  const symbols = [...text.matchAll(/MC_API\s+[^;]*?\b(mc_\w+)\s*\(/g)].map(match => match[1]);
  const structures = [...text.matchAll(/typedef struct (mc_\w+)\s*\{/g)].map(match => match[1]);
  const handles = [...text.matchAll(/typedef struct (mc_\w+)\s+\1;/g)].map(match => match[1]);
  const callbacks = [...text.matchAll(/\(MC_CALL \*(mc_\w+)\)/g)].map(match => match[1]);

  /* Both enum members and macros are public constants worth reviewing even
     though they do not appear as dynamic-library exports. */
  const enumConstants = [...text.matchAll(/enum(?:\s+\w+)?\s*\{([\s\S]*?)\}/g)]
    .flatMap(match => [...match[1].matchAll(/\b(MC_[A-Z0-9_]+)/g)].map(value => value[1]));
  const constants = [...new Set([...enumConstants,
    ...[...text.matchAll(/^#define (MC_[A-Z0-9_]+)/gm)].map(match => match[1])])].sort();
  declared.push(...symbols);
  inventory.push({ header, symbols, structures, handles, callbacks, constants });
}

if (JSON.stringify(declared.sort()) !== JSON.stringify(exportedSymbols)) {
  throw new Error('Public function declarations differ from ffi/exports.txt');
}

if (process.argv.includes('--check')) {
  /* Ownership and validation live in public headers and executable contract
     tests; this check protects the declaration/export correspondence only. */
  console.log(`Verified ${exportedSymbols.length} exports across ${headers.length} C headers.`);
} else {
  /* Emit documentation only on stdout so callers can review/regenerate it
     without this read-only audit silently rewriting repository files. */
  console.log('# Core C API declaration inventory\n\nGenerated by `node tests/scripts/audit-core-api.js`.\n');
  for (const entry of inventory) {
    console.log(`## ${entry.header}\n`);
    for (const [label, key] of [['Structures', 'structures'], ['Opaque handles', 'handles'],
      ['Callbacks', 'callbacks'], ['Constants and macros', 'constants'], ['Exports', 'symbols']]) {
      console.log(`${label}: ${entry[key].map(name => '`' + name + '`').join(', ') || 'none'}.\n`);
    }
  }
}
